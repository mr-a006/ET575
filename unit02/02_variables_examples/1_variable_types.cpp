#include <iostream>
#include <string>
using namespace std;

int main() {
    cout << "\n";

    // integers
    short s = 1;                            // Small integers
    int i = 1;                              
    long long l = 1;                        // Large integers
    unsigned int p = 1;                     // Postive integers
    unsigned long long bp = 1;              // Large positive integers
 
    // floating point
    float f = 1.0;                          // Small floats
    double d = 1.0;                         // Large floats and higher precision

    // other
    char c = '1';                           // Single character
    bool b = true;                          // True or false
 
    // complex data type
    string str = "1";                       // Zero, one or many characters

    cout << s << "\n";
    cout << i << "\n";
    cout << l << "\n";
    cout << p << "\n";
    cout << bp << "\n";            
    cout << f << "\n";
    cout << d << "\n";    
    cout << c << "\n";
    cout << b << "\n";
    cout << str << "\n";

    cout << "\n";
    return 0;
}
