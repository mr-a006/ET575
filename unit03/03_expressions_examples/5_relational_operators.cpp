#include <iostream>
using namespace std;

int main() {
    cout << "\n";
                                    // Relational operators
    cout << ( 5 > 6 ) << "\n";      // Greater than   
    cout << ( 5 < 6 ) << "\n";      // Less than   
    cout << ( 5 >= 6 ) << "\n";     // Greater than or equal to  
    cout << ( 5 <= 6 ) << "\n";     // Less than or equal to     
    cout << ( 5 == 6 ) << "\n";     // Equivalent 
    cout << ( 5 != 6 ) << "\n";     // Inequivalent   

    cout << "\n";
    return 0;
}
