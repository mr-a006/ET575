#include <iostream>
using namespace std;

int main() {
    cout << "\n";
                                    // Arithmetic operators
    cout << ( 5 + 6 ) << "\n";      // Addition
    cout << ( 5 - 6 ) << "\n";      // Subtraction
    cout << ( 5 * 6 ) << "\n";      // Multiplication
    cout << ( 5 / 6 ) << "\n";      // Division
    cout << ( 5 % 6 ) << "\n";      // Modulo division

    cout << "\n";
    return 0;
}
