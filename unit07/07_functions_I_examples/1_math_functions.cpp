#include <iostream>
#include <cmath>                    // cmath libary required for cmath functions to work
using namespace std;

int main() {
    cout << "\n";

    cout << sqrt(36) << "\n";       // return the square root of 36
    cout << pow(2,5) << "\n";       // return 2^5
    cout << abs(-50) << "\n";       // return the absolute value of 50
    cout << ceil(6.8) << "\n";      // return 6.8 rounded up
    cout << floor(6.8) << "\n";     // return 6.8 rounded down
    cout << round(6.8) << "\n";     // return 6.8 rounded to the nearest integer

    cout << "\n";
    return 0;
}
