#include <iostream>
#include <string>                    
using namespace std;                

int main() { 
    cout << endl;                       

    string name = "Joe";                    // Initialize a string variable with the literal "Joe"        
    cout << "Hello" << endl;                // Print a literal
    cout << name << endl;                   // Print a variable
    cout << "Hello " << name << endl;       // Print a literal and a variable
    
    cout << endl;  
    return 0;                       
}